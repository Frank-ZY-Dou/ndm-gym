"""Physical replay references for the native Adroit manipulation suite.

Data/assets are external. Every target is a control-boundary state generated by
replaying the original controls, not a kinematically assigned target trajectory.
"""
from __future__ import annotations

from dataclasses import dataclass
import json
from pathlib import Path

import numpy as np

DIMS = {'pen': (30, 30, 24), 'hammer': (33, 33, 26), 'relocate': (36, 36, 30)}


@dataclass(frozen=True)
class AdroitReference:
    qpos: np.ndarray
    qvel: np.ndarray
    actions: np.ndarray
    metadata: dict

    def __post_init__(self):
        m = self.metadata
        if m.get('kind') != 'adroit-suite-physical-replay-v1' or m.get('task') not in DIMS:
            raise ValueError('Expected identified native Adroit physical replay')
        nq, nv, nu = DIMS[m['task']]
        if (self.qpos.ndim != 2 or self.qpos.shape[1] != nq
                or self.qvel.shape != (len(self.qpos), nv)
                or self.actions.shape != (len(self.qpos)-1, nu) or len(self.actions) < 17):
            raise ValueError('Reference dimensions/horizon do not match task')
        if not all(np.isfinite(x).all() for x in (self.qpos, self.qvel, self.actions)):
            raise ValueError('Nonfinite reference')
        if len(m.get('joint_names', [])) != nq or len(set(m['joint_names'])) != nq:
            raise ValueError('Expected unique named scalar joints')
        if len(m.get('joint_types', [])) != nq or any(t not in (2, 3) for t in m['joint_types']):
            raise ValueError('Only native scalar hinge/slide coordinates are supported')
        if (len(m.get('joint_periodic', [])) != nq
                or any(type(x) is not bool for x in m['joint_periodic'])
                or set(m.get('scene', {})) != {'body_pos', 'body_quat', 'site_pos', 'site_quat'}):
            raise ValueError('Missing periodicity or scene identity')
        if (not np.isfinite(m.get('control_dt', 0)) or m.get('control_dt', 0) <= 0
                or type(m.get('frame_skip')) is not int or m['frame_skip'] <= 0):
            raise ValueError('Invalid physical control timestep')

    @property
    def frames(self):
        return len(self.qpos)

    def save(self, path):
        np.savez_compressed(path, qpos=self.qpos, qvel=self.qvel, actions=self.actions,
                            metadata=np.asarray(json.dumps(self.metadata, sort_keys=True)))

    @classmethod
    def load(cls, path: str | Path):
        with np.load(path, allow_pickle=False) as d:
            return cls(d['qpos'], d['qvel'], d['actions'], json.loads(str(d['metadata'])))
